import '@testing-library/jest-dom/vitest'

// jsdom does not implement matchMedia; provide a minimal stub so motion checks run.
if (!window.matchMedia) {
  window.matchMedia = (query) => ({
    matches: false,
    media: query,
    onchange: null,
    addEventListener() {},
    removeEventListener() {},
    addListener() {},
    removeListener() {},
    dispatchEvent() { return false },
  })
}
